'use strict';
/**
 * Recreate the VMS-SLA database on another engine.
 *
 * buildMigrationScript(db, dialect) returns one SQL script that
 *   1. creates all tables,
 *   2. loads every row from the SQLite database (ids preserved),
 *   3. adds foreign keys, indexes and integrity triggers (after the load, so
 *      append-only / lock triggers do not block the copy),
 *   4. resets identity counters past the highest copied id.
 *
 * loadDirect(db, dialect, connection) runs the same statements through the
 * optional `pg` or `oracledb` driver and verifies row counts afterwards.
 */
const { generate, splitStatements } = require('./ddl');
const { dependencyOrder, SCHEMA_VERSION } = require('./schema');

const ORACLE_CHUNK = 1000; // chars per TO_CLOB() piece; 1000 chars x 4 bytes stays under the 4000-byte literal limit

function quote(s) { return `'${String(s).replace(/'/g, "''")}'`; }

/**
 * Quoted string that never spans lines, so every INSERT stays on one line and
 * the script can be split safely: newlines become E'\\n' (PostgreSQL) or
 * CHR(10)/char(10) concatenation (Oracle/SQLite).
 */
function textLiteral(dialect, s) {
  s = String(s);
  if (!/[\r\n]/.test(s)) return quote(s);
  if (dialect === 'postgres') return `E'${s.replace(/\\/g, '\\\\').replace(/'/g, "''").replace(/\r/g, '\\r').replace(/\n/g, '\\n')}'`;
  const nlFn = dialect === 'oracle' ? 'CHR(10)' : 'char(10)';
  return s.replace(/\r/g, '').split('\n').map(quote).join(` || ${nlFn} || `);
}

function literal(dialect, col, v) {
  if (v === null || v === undefined) return 'NULL';
  const base = col.type.split(':')[0];
  if (['id', 'ref', 'int', 'num', 'bool'].includes(base)) {
    const n = Number(v);
    if (!Number.isFinite(n)) throw new Error(`Non-numeric value in ${col.name}: ${v}`);
    return String(n);
  }
  if (base === 'ts') {
    if (dialect === 'sqlite') return quote(v);
    const d = new Date(v);
    if (Number.isNaN(d.getTime())) throw new Error(`Invalid timestamp in ${col.name}: ${v}`);
    const iso = d.toISOString();
    if (dialect === 'postgres') return `${quote(iso)}::timestamptz`;
    return `TIMESTAMP '${iso.slice(0, 10)} ${iso.slice(11, 23)} +00:00'`;
  }
  if (base === 'date') {
    if (dialect === 'sqlite') return quote(v);
    const s = String(v).slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) throw new Error(`Invalid date in ${col.name}: ${v}`);
    return dialect === 'postgres' ? `${quote(s)}::date` : `DATE '${s}'`;
  }
  const s = String(v);
  if (dialect === 'oracle' && base === 'text') {
    const parts = [];
    for (let i = 0; i < s.length; i += ORACLE_CHUNK) parts.push(`TO_CLOB(${textLiteral(dialect, s.slice(i, i + ORACLE_CHUNK))})`);
    return parts.length ? parts.join(' || ') : 'NULL';
  }
  return textLiteral(dialect, s);
}

function dataStatements(db, dialect) {
  const out = [];
  for (const t of dependencyOrder()) {
    const cols = t.columns.map((c) => c.name);
    const rows = db.all(`SELECT ${cols.join(', ')} FROM ${t.name} ORDER BY ${t.columns[0].name}`);
    if (!rows.length) continue;
    out.push(`-- ${t.name}: ${rows.length} row(s)`);
    for (const row of rows) {
      out.push(`INSERT INTO ${t.name} (${cols.join(', ')}) VALUES (${t.columns.map((c) => literal(dialect, c, row[c.name])).join(', ')});`);
    }
  }
  return out;
}

function identityResets(dialect) {
  return dependencyOrder().map((t) => {
    const pk = t.columns.find((c) => c.type === 'id').name;
    if (dialect === 'postgres') return `SELECT setval(pg_get_serial_sequence('${t.name}', '${pk}'), COALESCE((SELECT MAX(${pk}) FROM ${t.name}), 0) + 1, false);`;
    if (dialect === 'oracle') return `ALTER TABLE ${t.name} MODIFY (${pk} GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE));`;
    return null;
  }).filter(Boolean);
}

function buildMigrationScript(db, dialect) {
  if (!['postgres', 'oracle', 'sqlite'].includes(dialect)) throw new Error(`Unsupported dialect ${dialect}`);
  const header = [
    '-- =====================================================================',
    '-- Bank of Palestine VMS-SLA - full database migration script',
    `-- Target: ${dialect}   Schema version: ${SCHEMA_VERSION}   Generated: ${new Date().toISOString()}`,
    '-- Contents: tables, data (ids preserved), constraints, indexes, triggers.',
    '-- Evidence and sealed PDF files are not in the database: copy the',
    '-- "evidence" and "documents" folders alongside (their SHA-256 hashes are).',
    '-- =====================================================================',
  ];
  const parts = [header.join('\n')];
  if (dialect === 'oracle') parts.push('SET DEFINE OFF\nWHENEVER SQLERROR EXIT FAILURE ROLLBACK');
  if (dialect === 'postgres') parts.push('\\set ON_ERROR_STOP on');
  parts.push(generate(dialect, { phase: 'tables', withHeader: false }));
  parts.push('-- ---------------------------------------------------------------- data');
  if (dialect === 'postgres' || dialect === 'sqlite') parts.push('BEGIN;');
  parts.push(dataStatements(db, dialect).join('\n'));
  parts.push('COMMIT;');
  parts.push(generate(dialect, { phase: 'constraints', withHeader: false }));
  const resets = identityResets(dialect);
  if (resets.length) parts.push('-- ---------------------------------------------------------------- identity counters\n' + resets.join('\n'));
  if (dialect === 'sqlite') parts.push(`PRAGMA user_version = ${SCHEMA_VERSION};`);
  return parts.join('\n\n') + '\n';
}

/** Executable statements (client directives such as SET / \set removed). */
function statementsFor(script, dialect) {
  const cleaned = script.split('\n').filter((l) => !/^(SET DEFINE|WHENEVER SQLERROR|\\set)/.test(l)).join('\n');
  return splitStatements(cleaned, dialect).filter((s) => !/^(BEGIN|COMMIT)$/i.test(s.replace(/;$/, '').trim()));
}

async function loadDirect(db, dialect, conn, { log = () => {} } = {}) {
  const script = buildMigrationScript(db, dialect);
  const stmts = statementsFor(script, dialect);
  if (dialect === 'postgres') {
    let pg;
    try { pg = require('pg'); } catch (_) { throw new Error('Install the PostgreSQL driver first: npm install pg'); }
    const client = new pg.Client(conn);
    await client.connect();
    try {
      await client.query('BEGIN');
      for (const [i, s] of stmts.entries()) {
        try { await client.query(s); } catch (e) { throw new Error(`Statement ${i + 1} failed: ${e.message}\n${s.slice(0, 400)}`); }
        if (i % 200 === 0) log(`  ${i}/${stmts.length}`);
      }
      await client.query('COMMIT');
      return await verifyCounts(db, async (t) => Number((await client.query(`SELECT COUNT(*) AS n FROM ${t}`)).rows[0].n));
    } catch (e) {
      await client.query('ROLLBACK').catch(() => {});
      throw e;
    } finally {
      await client.end();
    }
  }
  if (dialect === 'oracle') {
    let oracledb;
    try { oracledb = require('oracledb'); } catch (_) { throw new Error('Install the Oracle driver first: npm install oracledb'); }
    const c = await oracledb.getConnection(conn);
    try {
      for (const [i, s] of stmts.entries()) {
        try { await c.execute(s); } catch (e) { throw new Error(`Statement ${i + 1} failed: ${e.message}\n${s.slice(0, 400)}`); }
        if (i % 200 === 0) log(`  ${i}/${stmts.length}`);
      }
      await c.commit();
      return await verifyCounts(db, async (t) => Number((await c.execute(`SELECT COUNT(*) FROM ${t}`)).rows[0][0]));
    } finally {
      await c.close();
    }
  }
  throw new Error('Direct load supports postgres and oracle.');
}

async function verifyCounts(db, countFn) {
  const report = [];
  for (const t of dependencyOrder()) {
    const src = db.value(`SELECT COUNT(*) FROM ${t.name}`);
    const dst = await countFn(t.name);
    report.push({ table: t.name, source: src, target: dst, ok: src === dst });
  }
  return report;
}

module.exports = { buildMigrationScript, statementsFor, loadDirect, literal };
