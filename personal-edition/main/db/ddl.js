'use strict';
/**
 * DDL generator: turns the logical schema (./schema.js) into SQLite,
 * PostgreSQL or Oracle (12.2+) DDL, including integrity triggers that make
 * signed and locked records tamper-resistant at the database layer.
 *
 * generate(dialect, { phase }) phases:
 *   'tables'      CREATE TABLE (PK, NOT NULL, DEFAULT, UNIQUE, CHECK). SQLite also gets inline FKs.
 *   'constraints' FOREIGN KEYs (PG/Oracle), indexes, triggers.
 *   'all'         both (default)
 */
const { tables, dependencyOrder, SCHEMA_VERSION } = require('./schema');

const DIALECTS = ['sqlite', 'postgres', 'oracle'];

function colType(dialect, type) {
  const [base, len] = type.split(':');
  switch (dialect) {
    case 'sqlite':
      return { id: 'INTEGER', ref: 'INTEGER', str: 'TEXT', text: 'TEXT', int: 'INTEGER', num: 'REAL', bool: 'INTEGER', ts: 'TEXT', date: 'TEXT' }[base];
    case 'postgres':
      return { id: 'BIGINT', ref: 'BIGINT', str: `VARCHAR(${len})`, text: 'TEXT', int: 'INTEGER', num: 'NUMERIC(18,4)', bool: 'SMALLINT', ts: 'TIMESTAMPTZ', date: 'DATE' }[base];
    case 'oracle':
      return { id: 'NUMBER(19)', ref: 'NUMBER(19)', str: `VARCHAR2(${len} CHAR)`, text: 'CLOB', int: 'NUMBER(10)', num: 'NUMBER(18,4)', bool: 'NUMBER(1)', ts: 'TIMESTAMP WITH TIME ZONE', date: 'DATE' }[base];
    default:
      throw new Error(`Unknown dialect ${dialect}`);
  }
}

function literalDefault(dialect, col) {
  if (col.default === undefined) return '';
  const v = col.default;
  if (typeof v === 'number') return ` DEFAULT ${v}`;
  return ` DEFAULT '${String(v).replace(/'/g, "''")}'`;
}

const short = (s, n = 30) => (s.length <= n ? s : s.slice(0, n - 9) + '_' + hash8(s));
function hash8(s) {
  let h = 2166136261;
  for (const ch of s) h = Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0;
  return h.toString(16).padStart(8, '0');
}

function pkCol(t) { return t.columns.find((c) => c.type === 'id').name; }

function createTable(dialect, t) {
  const lines = [];
  for (const col of t.columns) {
    let line = `  ${col.name} ${colType(dialect, col.type)}`;
    if (col.type === 'id') {
      if (dialect === 'sqlite') line += ' PRIMARY KEY AUTOINCREMENT';
      else if (dialect === 'postgres') line += ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
      else line += ' GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY';
    } else {
      line += literalDefault(dialect, col);
      if (col.notNull) line += ' NOT NULL';
      if (dialect === 'sqlite' && col.type === 'ref') {
        line += ` REFERENCES ${col.references}(${pkCol(require('./schema').byName[col.references])})`;
      }
    }
    lines.push(line);
  }
  t.unique.forEach((cols, i) => lines.push(`  CONSTRAINT ${short(`uq_${t.name}_${i + 1}`)} UNIQUE (${cols.join(', ')})`));
  t.checks.forEach(([expr], i) => lines.push(`  CONSTRAINT ${short(`ck_${t.name}_${i + 1}`)} CHECK (${expr})`));
  for (const col of t.columns.filter((c) => c.type === 'bool')) {
    lines.push(`  CONSTRAINT ${short(`ck_${t.name}_${col.name}`)} CHECK (${col.name} IN (0,1))`);
  }
  return `CREATE TABLE ${t.name} (\n${lines.join(',\n')}\n);`;
}

function foreignKeys(dialect, t) {
  if (dialect === 'sqlite') return [];
  const schema = require('./schema');
  return t.columns
    .filter((c) => c.type === 'ref')
    .map((c) => `ALTER TABLE ${t.name} ADD CONSTRAINT ${short(`fk_${t.name}_${c.name}`)} FOREIGN KEY (${c.name}) REFERENCES ${c.references} (${pkCol(schema.byName[c.references])});`);
}

function indexes(dialect, t) {
  const out = [];
  t.indexes.forEach((cols, i) => {
    out.push(`CREATE INDEX ${short(`ix_${t.name}_${i + 1}`)} ON ${t.name} (${cols.join(', ')});`);
  });
  // FK columns on PG/Oracle are not indexed automatically.
  if (dialect !== 'sqlite') {
    const covered = new Set(t.indexes.map((cols) => cols[0]).concat(t.unique.map((u) => u[0])));
    t.columns.filter((c) => c.type === 'ref' && !covered.has(c.name)).forEach((c) => {
      out.push(`CREATE INDEX ${short(`ix_${t.name}_${c.name}`)} ON ${t.name} (${c.name});`);
    });
  }
  return out;
}

// ------------------------------------------------------------------ triggers
const MSG_APPEND = (t) => `${t} is append-only: records cannot be modified or deleted`;
const MSG_LOCKED = 'Incident report is locked: approved records cannot be modified';

function triggers(dialect, t) {
  const out = [];
  if (t.appendOnly) {
    if (dialect === 'sqlite') {
      out.push(`CREATE TRIGGER trg_${t.name}_no_upd BEFORE UPDATE ON ${t.name}\nBEGIN SELECT RAISE(ABORT, '${MSG_APPEND(t.name)}'); END;`);
      out.push(`CREATE TRIGGER trg_${t.name}_no_del BEFORE DELETE ON ${t.name}\nBEGIN SELECT RAISE(ABORT, '${MSG_APPEND(t.name)}'); END;`);
    } else if (dialect === 'postgres') {
      out.push(`CREATE TRIGGER trg_${t.name}_append_only BEFORE UPDATE OR DELETE ON ${t.name}\n  FOR EACH ROW EXECUTE FUNCTION vms_reject_change('${MSG_APPEND(t.name)}');`);
    } else {
      out.push(`CREATE OR REPLACE TRIGGER ${short(`trg_${t.name}_append_only`)}\nBEFORE UPDATE OR DELETE ON ${t.name}\nBEGIN\n  RAISE_APPLICATION_ERROR(-20001, '${MSG_APPEND(t.name)}');\nEND;\n/`);
    }
  }
  if (t.lockGuard === 'self') {
    if (dialect === 'sqlite') {
      out.push(`CREATE TRIGGER trg_${t.name}_lock_upd BEFORE UPDATE ON ${t.name}\nWHEN OLD.locked_at IS NOT NULL\nBEGIN SELECT RAISE(ABORT, '${MSG_LOCKED}'); END;`);
      out.push(`CREATE TRIGGER trg_${t.name}_lock_del BEFORE DELETE ON ${t.name}\nWHEN OLD.status <> 'DRAFT'\nBEGIN SELECT RAISE(ABORT, 'Only draft incident reports can be deleted'); END;`);
    } else if (dialect === 'postgres') {
      out.push(`CREATE TRIGGER trg_${t.name}_lock BEFORE UPDATE OR DELETE ON ${t.name}\n  FOR EACH ROW EXECUTE FUNCTION vms_guard_report();`);
    } else {
      out.push(`CREATE OR REPLACE TRIGGER trg_incident_report_lock\nBEFORE UPDATE OR DELETE ON incident_report\nFOR EACH ROW\nBEGIN\n  IF UPDATING AND :OLD.locked_at IS NOT NULL THEN\n    RAISE_APPLICATION_ERROR(-20002, '${MSG_LOCKED}');\n  END IF;\n  IF DELETING AND :OLD.status <> 'DRAFT' THEN\n    RAISE_APPLICATION_ERROR(-20003, 'Only draft incident reports can be deleted');\n  END IF;\nEND;\n/`);
    }
  }
  if (t.lockGuard === 'child') {
    if (dialect === 'sqlite') {
      for (const [ev, row] of [['INSERT', 'NEW'], ['UPDATE', 'OLD'], ['DELETE', 'OLD']]) {
        out.push(`CREATE TRIGGER trg_${t.name}_lock_${ev.slice(0, 3).toLowerCase()} BEFORE ${ev} ON ${t.name}\nWHEN (SELECT locked_at FROM incident_report WHERE report_id = ${row}.report_id) IS NOT NULL\nBEGIN SELECT RAISE(ABORT, '${MSG_LOCKED}'); END;`);
      }
    } else if (dialect === 'postgres') {
      out.push(`CREATE TRIGGER trg_${t.name}_lock BEFORE INSERT OR UPDATE OR DELETE ON ${t.name}\n  FOR EACH ROW EXECUTE FUNCTION vms_guard_report_child();`);
    } else {
      out.push(`CREATE OR REPLACE TRIGGER ${short(`trg_${t.name}_lock`)}\nBEFORE INSERT OR UPDATE OR DELETE ON ${t.name}\nFOR EACH ROW\nDECLARE\n  v_locked TIMESTAMP WITH TIME ZONE;\n  v_report NUMBER(19);\nBEGIN\n  v_report := CASE WHEN DELETING THEN :OLD.report_id ELSE :NEW.report_id END;\n  SELECT MAX(locked_at) INTO v_locked FROM incident_report WHERE report_id = v_report;\n  IF v_locked IS NOT NULL OR (UPDATING AND :OLD.report_id <> :NEW.report_id) THEN\n    RAISE_APPLICATION_ERROR(-20002, '${MSG_LOCKED}');\n  END IF;\nEND;\n/`);
    }
  }
  return out;
}

function preamble(dialect) {
  if (dialect === 'postgres') {
    return [
      `CREATE OR REPLACE FUNCTION vms_reject_change() RETURNS trigger LANGUAGE plpgsql AS $$\nBEGIN\n  RAISE EXCEPTION '%', TG_ARGV[0];\nEND;\n$$;`,
      `CREATE OR REPLACE FUNCTION vms_guard_report() RETURNS trigger LANGUAGE plpgsql AS $$\nBEGIN\n  IF TG_OP = 'UPDATE' AND OLD.locked_at IS NOT NULL THEN\n    RAISE EXCEPTION '${MSG_LOCKED}';\n  END IF;\n  IF TG_OP = 'DELETE' THEN\n    IF OLD.status <> 'DRAFT' THEN RAISE EXCEPTION 'Only draft incident reports can be deleted'; END IF;\n    RETURN OLD;\n  END IF;\n  RETURN NEW;\nEND;\n$$;`,
      `CREATE OR REPLACE FUNCTION vms_guard_report_child() RETURNS trigger LANGUAGE plpgsql AS $$\nDECLARE v_report BIGINT; v_locked TIMESTAMPTZ;\nBEGIN\n  IF TG_OP = 'DELETE' THEN v_report := OLD.report_id; ELSE v_report := NEW.report_id; END IF;\n  SELECT locked_at INTO v_locked FROM incident_report WHERE report_id = v_report;\n  IF v_locked IS NOT NULL OR (TG_OP = 'UPDATE' AND OLD.report_id <> NEW.report_id) THEN\n    RAISE EXCEPTION '${MSG_LOCKED}';\n  END IF;\n  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;\n  RETURN NEW;\nEND;\n$$;`,
    ];
  }
  return [];
}

function header(dialect) {
  const label = { sqlite: 'SQLite 3.35+', postgres: 'PostgreSQL 13+', oracle: 'Oracle Database 12.2+ (19c/23ai recommended)' }[dialect];
  return [
    '-- =====================================================================',
    '-- Bank of Palestine - Vendor Management & SLA Platform (VMS-SLA)',
    `-- Schema version ${SCHEMA_VERSION} - generated DDL for ${label}`,
    '-- Generated from main/db/schema.js. Do not edit by hand; regenerate with',
    `--   node scripts/export-ddl.js --dialect ${dialect}`,
    '-- =====================================================================',
    '',
  ].join('\n');
}

function generate(dialect, { phase = 'all', withHeader = true } = {}) {
  if (!DIALECTS.includes(dialect)) throw new Error(`Unsupported dialect "${dialect}". Use one of ${DIALECTS.join(', ')}`);
  const ordered = dependencyOrder();
  const parts = [];
  if (withHeader) parts.push(header(dialect));
  if (phase === 'all' || phase === 'tables') {
    parts.push('-- ---------------------------------------------------------------- tables');
    for (const t of ordered) parts.push(createTable(dialect, t));
  }
  if (phase === 'all' || phase === 'constraints') {
    if (dialect !== 'sqlite') {
      parts.push('-- ---------------------------------------------------------------- foreign keys');
      for (const t of ordered) parts.push(...foreignKeys(dialect, t));
    }
    parts.push('-- ---------------------------------------------------------------- indexes');
    for (const t of ordered) parts.push(...indexes(dialect, t));
    parts.push('-- ---------------------------------------------------------------- integrity triggers');
    parts.push(...preamble(dialect));
    for (const t of ordered) parts.push(...triggers(dialect, t));
  }
  return parts.join('\n\n') + '\n';
}

/**
 * Split a generated script into executable statements. Oracle PL/SQL blocks end
 * with a line containing only "/"; PG functions use $$ quoting.
 */
function splitStatements(sql, dialect) {
  const lines = sql.split('\n').filter((l) => !l.startsWith('--'));
  const stmts = [];
  let buf = [];
  let inDollar = false;
  let inPlsql = false;
  for (const line of lines) {
    if (dialect === 'oracle' && line.trim() === '/') {
      stmts.push(buf.join('\n').trim());
      buf = [];
      inPlsql = false;
      continue;
    }
    buf.push(line);
    if (dialect === 'oracle' && /^CREATE OR REPLACE TRIGGER/.test(line)) inPlsql = true;
    if (dialect === 'postgres' && (line.match(/\$\$/g) || []).length % 2 === 1) inDollar = !inDollar;
    if (dialect === 'sqlite' && /^CREATE TRIGGER/.test(line)) inPlsql = true;
    if (dialect === 'sqlite' && inPlsql && /END;\s*$/.test(line)) {
      stmts.push(buf.join('\n').trim());
      buf = [];
      inPlsql = false;
      continue;
    }
    if (!inDollar && !inPlsql && /;\s*$/.test(line)) {
      let s = buf.join('\n').trim();
      if (dialect === 'oracle') s = s.replace(/;\s*$/, '');
      if (s) stmts.push(s);
      buf = [];
    }
  }
  const rest = buf.join('\n').trim();
  if (rest) stmts.push(rest);
  return stmts.filter(Boolean);
}

module.exports = { generate, splitStatements, colType, DIALECTS, tables };
